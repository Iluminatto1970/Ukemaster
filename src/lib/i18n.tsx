/** Detecta o idioma do navegador (pt-BR → pt, en-US → en, fallback pt). */
function detectBrowserLang(): Lang {
  try {
    const nav = navigator.language || (navigator as { userLanguage?: string }).userLanguage || '';
    const base = nav.toLowerCase().slice(0, 2);
    if (base === 'pt') return 'pt';
    if (base === 'en') return 'en';
    if (base === 'es') return 'es';
    if (base === 'fr') return 'fr';
    if (base === 'de') return 'de';
    if (base === 'ja') return 'ja';
    if (base === 'zh') return 'zh';
    if (base === 'ar') return 'ar';
  } catch {
    // sem navigator (SSR) — português
  }
  return 'pt';
}

interface I18nContextValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  /** Traduz uma chave; retorna a própria chave se não existir no idioma. */
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextValue>({
  lang: 'pt',
  setLang: () => undefined,
  // Fora do provider (testes/SSR), cai para o português em vez de expor a
  // chave crua na tela.
  t: (k) => pt[k] ?? k,
});

const STORAGE_KEY = 'ukemaster_lang_v1';

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as Lang | null;
      if (saved && DICTS[saved]) return saved;
    } catch {
      // storage indisponível — detecta do navegador
    }
    return detectBrowserLang();
  });

  // Aplica lang + direção (RTL para árabe) no <html>
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = RTL_LANGS.has(lang) ? 'rtl' : 'ltr';
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      // cota cheia/privado — a troca vale para a sessão
    }
  };

  const value = useMemo<I18nContextValue>(() => {
    const dict = DICTS[lang];
    return {
      lang,
      setLang,
      t: (key: string) => dict[key] ?? pt[key] ?? key,
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export function useT() {
  return useContext(I18nContext);
}
